/// The built-in `(code, Unicode, width)` table of a symbolic standard-14
/// face — Symbol (and Monotype's `SymbolMT` clone, which shares its layout)
/// or ZapfDingbats — or `None` for any other font. `base` as in
/// [`widths_for`].
pub(crate) fn symbolic_builtin(base: &[u8]) -> Option<&'static [(u8, u32, u16)]> {
    let lower = std::str::from_utf8(base).ok()?.trim().to_ascii_lowercase();
    let family = lower.split([',', '-']).next().unwrap_or("").trim();
    match family {
        "symbol" | "symbolmt" => Some(SYMBOL),
        "zapfdingbats" | "itczapfdingbats" => Some(ZAPF_DINGBATS),
        _ => None,
    }
}

/// For a Symbol-family face: its ASCII letters mapped to the glyphs Symbol
/// actually draws at those codes (`m` → µ, `W` → Ω, `a` → α). Symbol has no
/// Latin letters, so a `ToUnicode` entry naming one is the producer
/// mislabelling a Greek glyph by its code -- seen in office exports that
/// embed Symbol as a CID font. `None` for any other face.
pub(crate) fn symbol_letter_remap(base: &[u8]) -> Option<std::collections::HashMap<char, char>> {
    let table = symbolic_builtin(base)?;
    if !std::ptr::eq(table, SYMBOL) {
        return None;
    }
    Some(
        table
            .iter()
            .filter(|&&(code, _, _)| code.is_ascii_alphabetic())
            .filter_map(|&(code, cp, _)| char::from_u32(cp).map(|ch| (code as char, ch)))
            .collect(),
    )
}

/// Width table for a normalized standard-14 family, or `None` when the face
/// is not one of the twelve text faces (Symbol/ZapfDingbats included).
/// `base` is the `/BaseFont` name with any `ABCDEF+` subset prefix stripped.
pub(crate) fn widths_for(base: &[u8]) -> Option<Std14Widths> {
    // Aliases per the PDF spec's standard-14 substitution table: Arial ->
    // Helvetica, TimesNewRoman -> Times, CourierNew -> Courier; a `,Bold` /
    // `,Italic` / `-Bold` / `-Oblique` suffix picks the face.
    let s = std::str::from_utf8(base).ok()?.trim();
    let lower = s.to_ascii_lowercase();
    let (family, style) = match lower.split_once(['-', ',']) {
        Some((f, st)) => (f.trim().to_string(), st.trim().to_string()),
        None => (lower.clone(), String::new()),
    };
    let bold = style.contains("bold");
    let italic = style.contains("italic") || style.contains("oblique");
    match family.as_str() {
        "courier" | "couriernew" => Some(Std14Widths::Fixed(COURIER_WIDTH)),
        "helvetica" | "arial" => Some(Std14Widths::Table(if bold {
            HELVETICA_BOLD
        } else {
            HELVETICA
        })),
        "times" | "timesnewroman" => Some(Std14Widths::Table(match (bold, italic) {
            (true, true) => TIMES_BOLD_ITALIC,
            (true, false) => TIMES_BOLD,
            (false, true) => TIMES_ITALIC,
            (false, false) => TIMES_ROMAN,
        })),
        _ => symbolic_builtin(base).map(Std14Widths::Symbolic),
    }
}

/// A standard-14 face's metrics: fixed-pitch, or a sorted `(codepoint, width)`
/// table in 1000-unit glyph space.
pub(crate) enum Std14Widths {
    Fixed(f64),
    Table(&'static [(u32, u16)]),
    /// A symbolic face's code-keyed built-in table (see [`symbolic_builtin`]).
    Symbolic(&'static [(u8, u32, u16)]),
}

impl Std14Widths {
    /// The advance for `ch`, or `None` when the face has no such glyph.
    pub(crate) fn width(&self, ch: char) -> Option<f64> {
        match self {
            Std14Widths::Fixed(w) => Some(*w),
            Std14Widths::Table(t) => t
                .binary_search_by_key(&(ch as u32), |&(cp, _)| cp)
                .ok()
                .map(|i| f64::from(t[i].1)),
            Std14Widths::Symbolic(t) => t
                .iter()
                .find(|&&(_, cp, _)| cp == ch as u32)
                .map(|&(_, _, w)| f64::from(w)),
        }
    }
}
